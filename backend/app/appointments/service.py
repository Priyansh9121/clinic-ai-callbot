logger = get_logger(__name__)


@dataclass(frozen=True, slots=True)
class StaffAuthorised:
    """The caller is authorised by something other than owning the record.

    Cancel and reschedule take an owner check that cannot be defaulted away.
    The two legitimate authorisations look different at the call site on
    purpose: the conversation engine passes the patient id it verified, and the
    staff API passes this, naming the mechanism that authorised it instead.

    Before this existed the parameter defaulted to None, so "staff are
    authorised by their API key" and "somebody forgot the owner check" were the
    same call. A third mutating flow that omitted it would have type-checked,
    passed every test in which a caller cancels their own booking, and accepted
    any appointment id the session happened to hold.
    """

    #: Which mechanism. Recorded so the audit row says why this was allowed.
    mechanism: str


#: Either the patient who must own the record, or an explicit statement that
#: ownership is not the authorisation. There is no third option and no default.
OwnerCheck = uuid.UUID | StaffAuthorised


@dataclass(frozen=True, slots=True)
class BookingRequest:
    """A fully-resolved booking instruction.

    Every field is a concrete database id or validated value. Nothing here is
    free text from a caller or generated by a language model — the conversation
    engine resolves names and dates to ids *before* constructing this.
    """

    clinic_id: uuid.UUID
    patient_id: uuid.UUID
    slot_id: uuid.UUID
    #: Required, with no default, for the same reason ``owner`` is: it gates a
    #: policy check and ``False`` is the permissive branch.
    #: ``_enforce_booking_rules`` reads ``if is_new_patient and not
    #: appointment_type.new_patient_allowed``, so a caller who omitted it had
    #: the appointment type approved whether or not the clinic allows new
    #: patients on it. Every caller already knows the answer; the default only
    #: let a future one forget to say.
    is_new_patient: bool
    source: BookingSource = BookingSource.AI_CALLBOT
    reason_summary: str | None = None
    #: Deliberately optional. Omitting it loses idempotent *replay* — a retry
    #: raises rather than returning the original booking — but no invariant
    #: becomes reachable: the partial unique indexes on the slot and on
    #: (patient, start_time) still refuse the second appointment. The database
    #: prevents the harm; this only makes the retry graceful.
    idempotency_key: str | None = None
    #: Deliberately optional, and the weakest of the four. Omitting it writes an
    #: audit row with no attribution rather than no audit row, so the trail
    #: still cannot claim something happened that did not.
    actor_ref: str | None = None


@dataclass(frozen=True, slots=True)
class BookingResult:
    appointment: Appointment
    replayed: bool = False  # True when an idempotency key matched an existing booking


class AppointmentService:
    def __init__(self, session: AsyncSession, settings: Settings) -> None:
        self._session = session
        self._settings = settings
        self._audit = AuditService(session)

    # --- Booking -----------------------------------------------------------
    @asynccontextmanager
    async def _atomic(self) -> AsyncIterator[None]:
        """One appointment mutation: committed together, or undone together.

        The session is shared with the rest of the conversation. A caller who
        is new to the clinic has a provisional patient record created on it
        earlier in the same call, and that record is not committed until the
        turn ends — so rolling the session back wholesale when a booking failed
        deleted the caller as well as the failed booking. The next turn then
        could not find the patient it had just created.

        A SAVEPOINT scopes the undo to what this unit wrote. Everything another
        service already put in the outer transaction survives, and the commit
        that follows a success still makes the patient and the appointment real
        together — which is the property that matters: no caller is told an
        appointment exists before PostgreSQL agrees.
        """
        try:
            async with self._session.begin_nested():
                yield
            await self._session.commit()
        except IntegrityError as exc:
            # The partial unique indexes are the backstop for a slot that was
            # taken between the lock and the flush.
            await self._session.rollback()
            raise _translate_integrity_error(exc) from exc

    async def book(self, request: BookingRequest) -> BookingResult:
        started = utc_now()
        try:
            async with self._atomic():
                result = await self._book_inner(request)
        except Exception as exc:
            metrics.increment(M.BOOKING_FAILURE, labels={"reason": type(exc).__name__})
            raise
        await self._load_related(result.appointment)
        if not result.replayed:
            logger.info(
                "booking.confirmed",
                appointment_id=str(result.appointment.id),
                source=request.source.value,
            )
        metrics.increment(M.BOOKING_SUCCESS, labels={"source": request.source.value})
        metrics.observe(M.BOOKING_LATENCY, (utc_now() - started).total_seconds() * 1000)
        return result

    async def _book_inner(self, request: BookingRequest) -> BookingResult:
        # 1. Idempotency: a retried request must not create a second booking.
        if request.idempotency_key:
            existing = await self._find_by_idempotency_key(request.idempotency_key)
            if existing is not None:
                logger.info("booking.idempotent_replay", appointment_id=str(existing.id))
                return BookingResult(appointment=existing, replayed=True)

        patient = await self._session.get(Patient, request.patient_id)
        if patient is None or not patient.active or patient.clinic_id != request.clinic_id:
            raise PatientNotFoundError()

        # 2. Lock the slot. Competing bookers serialise here.
        slot = await self._lock_slot(request.slot_id)

        # 3. Re-verify under the lock — the read that found this slot is stale.
        if slot.status != SlotStatus.AVAILABLE:
            raise SlotUnavailableError(
                detail=f"slot {slot.id} is {slot.status.value}",
                context={"slot_id": str(slot.id)},
            )

        self._enforce_booking_rules(slot, is_new_patient=request.is_new_patient)

        # 4. Create the appointment and consume the slot in the same transaction.
        appointment = Appointment(
            clinic_id=request.clinic_id,
            patient_id=patient.id,
            practitioner_id=slot.practitioner_id,
            location_id=slot.location_id,
            appointment_type_id=slot.appointment_type_id,
            availability_slot_id=slot.id,
            start_time=slot.start_time,
            end_time=slot.end_time,
            status=AppointmentStatus.CONFIRMED,
            booking_source=request.source,
            reason_summary=_truncate(request.reason_summary, 280),
            idempotency_key=request.idempotency_key,
        )
        self._session.add(appointment)
        slot.status = SlotStatus.BOOKED
        slot.held_until = None
        # Flush so the primary key is assigned before the audit row references
        # it; without this the audit event records a null subject.
        await self._session.flush()

        self._audit.record(
            action=AuditAction.APPOINTMENT_CREATED,
            actor_type=_actor_for(request.source),
            actor_ref=request.actor_ref,
            clinic_id=request.clinic_id,
            subject_type="appointment",
            subject_id=appointment.id,
            metadata={
                "source": request.source.value,
                "slot_id": str(slot.id),
                "practitioner_id": str(slot.practitioner_id),
                "start_time": slot.start_time.isoformat(),
            },
        )

        # 5. The commit lives in _atomic(), which owns the transaction
        #    boundary. Only after it returns is the booking real.
        return BookingResult(appointment=appointment)

    def _enforce_booking_rules(self, slot: AvailabilitySlot, *, is_new_patient: bool) -> None:
        """Clinic policy checks. Deterministic — never delegated to a model."""
        appointment_type = slot.appointment_type
        min_start = utc_now() + timedelta(minutes=self._settings.booking_lead_minutes)
        if slot.start_time < min_start:
            raise BookingRuleError(
                detail="slot is inside the minimum booking lead time",
                public_message="That time is too soon to book over the phone.",
            )
        if is_new_patient and not appointment_type.new_patient_allowed:
            raise BookingRuleError(
                detail="appointment type does not accept new patients",
                public_message="That appointment type isn't available for new patients.",
            )
        if not appointment_type.active:
            raise BookingRuleError(detail="appointment type is inactive")

    # --- Cancellation ------------------------------------------------------
    async def cancel(
        self,
        appointment_id: uuid.UUID,
        *,
        owner: OwnerCheck,
        reason: str | None = None,
        source: BookingSource = BookingSource.AI_CALLBOT,
        actor_ref: str | None = None,
    ) -> Appointment:
        """Cancel and release the slot back to AVAILABLE.

        ``owner`` is an authorisation check, not a filter: the conversation
        engine passes the verified patient so a caller can never cancel someone
        else's appointment by guessing an id. It has no default — a caller that
        is authorised some other way must say so with ``StaffAuthorised``
        rather than by omitting the argument.
        """
        async with self._atomic():
            appointment = await self._lock_appointment(appointment_id)
            if isinstance(owner, uuid.UUID) and appointment.patient_id != owner:
                # Same error as "not found" — no information disclosure.
                raise AppointmentNotFoundError()
            if appointment.status != AppointmentStatus.CONFIRMED:
                raise AppointmentStateError(
                    detail=f"appointment is {appointment.status.value}",
                    public_message="That appointment is already cancelled.",
                )

            appointment.status = AppointmentStatus.CANCELLED
            appointment.cancelled_at = utc_now()
            appointment.cancellation_reason = _truncate(reason, 500)

            if appointment.availability_slot_id:
                slot = await self._lock_slot(appointment.availability_slot_id, missing_ok=True)
                # Only re-open a future slot; a past one stays consumed.
                if slot and slot.status == SlotStatus.BOOKED:
                    slot.status = (
                        SlotStatus.AVAILABLE if slot.start_time > utc_now() else SlotStatus.BLOCKED
                    )

            self._audit.record(
                action=AuditAction.APPOINTMENT_CANCELLED,
                actor_type=_actor_for(source),
                actor_ref=actor_ref,
                clinic_id=appointment.clinic_id,
                subject_type="appointment",
                subject_id=appointment.id,
                metadata={"source": source.value, "reason_code": "caller_request"},
            )

        metrics.increment(M.CANCELLATION, labels={"source": source.value})
        logger.info("booking.cancelled", appointment_id=str(appointment.id))
        return appointment

    # --- Rescheduling ------------------------------------------------------
    async def reschedule(
        self,
        appointment_id: uuid.UUID,
        new_slot_id: uuid.UUID,
        *,
        owner: OwnerCheck,
        source: BookingSource = BookingSource.AI_CALLBOT,
        actor_ref: str | None = None,
        idempotency_key: str | None = None,
    ) -> Appointment:
        """Move an appointment to a new slot, atomically.

        Either both sides commit, or neither does: the caller is never left
        without their original appointment because the new slot was taken.
        """
        if idempotency_key:
            existing = await self._find_by_idempotency_key(idempotency_key)
            if existing is not None:
                return existing

        async with self._atomic():
            # Lock order: appointment, then slot — matches book()/cancel().
            original = await self._lock_appointment(appointment_id)
            if isinstance(owner, uuid.UUID) and original.patient_id != owner:
                raise AppointmentNotFoundError()
            if original.status != AppointmentStatus.CONFIRMED:
                raise AppointmentStateError(
                    detail=f"appointment is {original.status.value}",
                    public_message="That appointment can no longer be changed.",
                )

            new_slot = await self._lock_slot(new_slot_id)
            if new_slot.status != SlotStatus.AVAILABLE:
                raise SlotUnavailableError(context={"slot_id": str(new_slot.id)})
            self._enforce_booking_rules(new_slot, is_new_patient=False)

            old_slot_id = original.availability_slot_id
            replacement = Appointment(
                clinic_id=original.clinic_id,
                patient_id=original.patient_id,
                practitioner_id=new_slot.practitioner_id,
                location_id=new_slot.location_id,
                appointment_type_id=new_slot.appointment_type_id,
                availability_slot_id=new_slot.id,
                start_time=new_slot.start_time,
                end_time=new_slot.end_time,
                status=AppointmentStatus.CONFIRMED,
                booking_source=source,
                reason_summary=original.reason_summary,
                idempotency_key=idempotency_key,
            )
            self._session.add(replacement)

            # Retire the original first so the partial unique index on
            # (patient_id, start_time) cannot trip when moving within a day.
            original.status = AppointmentStatus.CANCELLED
            original.cancelled_at = utc_now()
            original.cancellation_reason = "rescheduled"
            await self._session.flush()
            original.rescheduled_to_id = replacement.id

            new_slot.status = SlotStatus.BOOKED
            if old_slot_id:
                old_slot = await self._lock_slot(old_slot_id, missing_ok=True)
                if old_slot and old_slot.status == SlotStatus.BOOKED:
                    old_slot.status = (
                        SlotStatus.AVAILABLE
                        if old_slot.start_time > utc_now()
                        else SlotStatus.BLOCKED
                    )

            self._audit.record(
                action=AuditAction.APPOINTMENT_RESCHEDULED,
                actor_type=_actor_for(source),
                actor_ref=actor_ref,
                clinic_id=original.clinic_id,
                subject_type="appointment",
                subject_id=replacement.id,
                metadata={
                    "previous_appointment_id": str(original.id),
                    "slot_id": str(new_slot.id),
                    "start_time": new_slot.start_time.isoformat(),
                },
            )

        await self._load_related(replacement)
        metrics.increment(M.RESCHEDULE, labels={"source": source.value})
        logger.info(
            "booking.rescheduled",
            appointment_id=str(replacement.id),
            previous_id=str(original.id),
        )
        return replacement

    # --- Queries -----------------------------------------------------------
    async def get(self, appointment_id: uuid.UUID) -> Appointment:
        appointment = await self._session.get(Appointment, appointment_id)
        if appointment is None:
            raise AppointmentNotFoundError()
        return appointment

    async def upcoming_for_patient(
        self, patient_id: uuid.UUID, *, limit: int = 10
    ) -> list[Appointment]:
        result = await self._session.execute(
            select(Appointment)
            .where(
                Appointment.patient_id == patient_id,
                Appointment.status == AppointmentStatus.CONFIRMED,
                Appointment.start_time >= utc_now(),
            )
            .order_by(Appointment.start_time)
            .limit(limit)
        )
        return list(result.scalars().unique().all())

    # --- Internals ---------------------------------------------------------
    async def _lock_slot(self, slot_id: uuid.UUID, *, missing_ok: bool = False) -> AvailabilitySlot:
        result = await self._session.execute(
            select(AvailabilitySlot)
            .where(AvailabilitySlot.id == slot_id)
            # The model eager-loads its relationships with a join, and
            # PostgreSQL refuses FOR UPDATE on the nullable side of an outer
            # join. selectinload fetches them in separate statements, so the
            # locking query stays a plain single-table SELECT.
            .options(
                selectinload(AvailabilitySlot.appointment_type),
                selectinload(AvailabilitySlot.practitioner),
                selectinload(AvailabilitySlot.location),
            )
            .with_for_update()
        )
        slot = result.scalars().first()
        if slot is None:
            if missing_ok:
                return None  # type: ignore[return-value]
            raise SlotNotFoundError()
        return slot

    async def _lock_appointment(self, appointment_id: uuid.UUID) -> Appointment:
        result = await self._session.execute(
            select(Appointment)
            .where(Appointment.id == appointment_id)
            .options(
                selectinload(Appointment.patient),
                selectinload(Appointment.practitioner),
                selectinload(Appointment.location),
                selectinload(Appointment.appointment_type),
            )
            .with_for_update()
        )
        appointment = result.scalars().first()
        if appointment is None:
            raise AppointmentNotFoundError()
        return appointment

    async def _load_related(self, appointment: Appointment) -> None:
        """Populate relationships before returning a freshly created row.

        A newly constructed ``Appointment`` has ids but no loaded relationships,
        and touching one after the commit would trigger a lazy load outside the
        async context. That raised *after* the booking was durable, so the
        caller was told the booking failed when it had actually succeeded —
        loading eagerly here removes that failure mode for every caller.
        """
        await self._session.refresh(
            appointment,
            attribute_names=["practitioner", "patient", "location", "appointment_type"],
        )

    async def _find_by_idempotency_key(self, key: str) -> Appointment | None:
        result = await self._session.execute(
            select(Appointment).where(Appointment.idempotency_key == key)
        )
        return result.scalars().first()


def _actor_for(source: BookingSource) -> ActorType:
    return {
        BookingSource.AI_CALLBOT: ActorType.AI_CALLBOT,
        BookingSource.RECEPTION: ActorType.STAFF,
        BookingSource.ONLINE: ActorType.PATIENT,
    }[source]


def _truncate(value: str | None, length: int) -> str | None:
    if value is None:
        return None
    value = value.strip()
    return value[:length] if value else None


def _translate_integrity_error(exc: IntegrityError) -> Exception:
    """Map a constraint violation to a domain error the caller can act on."""
    constraint = (getattr(exc.orig, "constraint_name", None) or str(exc.orig)).lower()
    if "active_slot" in constraint:
        return SlotUnavailableError(detail="slot already has a confirmed appointment")
    if "active_prac_time" in constraint:
        return SlotUnavailableError(detail="practitioner already booked at that time")
    if "active_pat_time" in constraint:
        return DuplicateBookingError(
            detail="patient already has an appointment at that time",
            public_message="You already have an appointment at that time.",
        )
    if "idempotency_key" in constraint:
        return DuplicateBookingError(detail="duplicate idempotency key")
    return SlotUnavailableError(detail=f"integrity violation: {constraint[:120]}")
