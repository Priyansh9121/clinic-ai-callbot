"""Transactional appointment booking, cancellation and rescheduling.

The rule this module exists to enforce: **the callbot may only tell a caller
their appointment is booked after PostgreSQL has committed it.** Every public
method therefore either commits and returns a persisted row, or raises. There
is no intermediate "probably booked" state.

Concurrency strategy
--------------------
1. ``SELECT ... FOR UPDATE`` on the availability slot serialises competing
   bookers on that row. A second booker blocks until the first commits, then
   re-reads and sees ``BOOKED``.
2. Partial unique indexes (see ``app.database.models.appointment``) are the
   backstop: even if a future code path skips the lock, the database refuses
   the second insert and we translate the ``IntegrityError`` into a clean
   ``SlotUnavailableError``.
3. Locks are always taken in the order *appointment → slot*, consistently
   across all three operations, so two concurrent reschedules cannot deadlock.
"""

from __future__ import annotations

import uuid
from collections.abc import AsyncIterator
from contextlib import asynccontextmanager
from dataclasses import dataclass
from datetime import timedelta

from sqlalchemy import select
